        export_excel_action.setShortcut(QKeySequence("Ctrl+Shift+E"))
        self.recover_project_action = QAction("Recover autosaved session…", self, triggered=self.offer_autosave_recovery)
        self.recover_project_action.setEnabled(self._recovery_path.exists())
